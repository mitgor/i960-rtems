#!/usr/bin/env python3
"""Independent Python oracle, including every untouched byte and both guards."""
from pathlib import Path
rows=[]
fractions=[0,0xffffffff,0x80000000,0x7fffffff,0x007fffff,0x00ff0000]
steps=[0,65536,0xffffffff,0x70000000,0x80010000,0x00008001]
counts=[0,1,2,199,200,127]
for length in [-1,0,1,2,7,127,128,255]:
 for k,frac in enumerate(fractions):
  n=counts[k];step=steps[k];double=(k+length)&1
  b=bytearray([0xa5])*64032
  f=frac
  for i in range(n):
   idx=(f if f<0x80000000 else f-0x100000000)>>16
   idx=max(0,min(length-1,idx)) if length>0 else idx&127
   pixel=(((idx*73+19)&255)*29+11)&255
   b[16+i*320]=pixel
   if double:b[23+i*320]=pixel # deliberately nonadjacent destinations
   f=(f+step)&0xffffffff
  h=2166136261
  for v in b:h=((h^v)*16777619)&0xffffffff
  rows.append('{%du, %du, %du, %d, %du, 0x%08xu}'%(frac,step,n,length,double,h))
p=Path(__file__).with_name('vectors.h')
p.write_text('/* Generated by generate_vectors.py; Python integer oracle. */\nstatic const struct vector {unsigned frac,step,count;int length;unsigned dual,hash;} vectors[]={\n'+',\n'.join(rows)+'\n};\n')
